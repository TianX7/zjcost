def main() -> int:
    assert all(len(r) == 9 for r in ROWS), "存在字段数不为 9 的行"
    assert len({r[0] for r in ROWS}) == len(ROWS), "存在重复编码"

    ok, fail = 0, 0
    for idx, row in enumerate(ROWS, start=1):
        (code, name, unit, method, price, site, part, grade, note) = row
        level = SITES[site]
        ratio = COST_RATIO[method]
        payload = {
            "quota_code": code,
            "name": name,
            "unit": unit,
            "acquisition_method": method,
            "base_price": price,
            "labor_qty": round(price * ratio[0], 2),
            "material_qty": round(price * ratio[1], 2),
            "machine_qty": round(price * ratio[2], 2),
            "chapter": CHAPTER,
            "version": VERSION,
            "heritage_site": site,
            "relic_level": level,
            "repair_part": part,
            "condition_grade": grade,
            "batch_no": f"{'HS' if method == 'recycle' else 'FX'}-26{idx:03d}",
            "inspection_report_no": f"JC-26{idx:03d}",
            "origin_note": note,
            "work_content": f"{name}：包括{'回收' if method == 'recycle' else '复现制作'}、检验、运输及现场堆放",
            "applicable_scope": "遗址修复工程中旧材料获取与使用",
        }
        try:
            r = requests.post(API, json=payload, timeout=10)
            if r.status_code == 200:
                ok += 1
            else:
                fail += 1
                print(f"[FAIL] {code} HTTP {r.status_code}: {r.text[:120]}")
        except Exception as exc:
            fail += 1
            print(f"[ERR] {code}: {exc}")

    print(f"导入完成: 成功 {ok} / 失败 {fail} / 共 {len(ROWS)} 条")

    # 验证统计
    stats = requests.get(API + "/stats", timeout=10).json()
    print(f"\n库内旧材料总数: {stats['total']}")
    for m in stats["by_acquisition_method"]:
        print(f"  {m['acquisition_method']}: {m['count']} 条")
    print(f"涉及遗址: {len(stats.get('by_heritage_site', []))} 处")
    for s in stats.get("by_heritage_site", []):
        print(f"  {s['heritage_site']}: {s['count']} 条")
    return 0 if fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
